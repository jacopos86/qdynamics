#!/usr/bin/env python3
"""Emit the next submit file of this lane from a returned segment's receipt.

A segment of this lane returns one of two states that continue the campaign,
and the receipt says which:

  stop_reason = wall_budget   the segment stopped at an accepted step short
                              of its own final_time; the continuation is the
                              *same* final_time again, resumed from the
                              checkpoint this segment left, under a fresh
                              run id.
  stop_reason = final_time    the segment reached its final_time; the
                              continuation is the *next* segment, resumed
                              from the checkpoint this segment left.

Both continuations differ from the shipped submit files in the run id, the
fifth argument (initial_state_file), transfer_input_files, the output and
error file names and +JobBatchName, so neither can be run by resubmitting a
shipped file.  This script writes the continuation instead of asking for five
hand edits, and it refuses to write a run id that any raw_outputs directory
or any submit file in the lane already names, so a stage-out can never
replace the checkpoint it was resumed from.

Usage (on the AP, from the submit root):

  python3 chtc/paper_v_cwrmf_event_guard_accel_20260915/make_resume_submit.py \
      archives_by_receipt/<sha>/receipt.json

A run's own summary.json is accepted in place of the receipt:

  python3 .../make_resume_submit.py \
      raw_outputs/<campaign>/<run_id>/summary.json

The path written is printed on the last line of stdout.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

LANE_RELATIVE_PATH = "chtc/paper_v_cwrmf_event_guard_accel_20260915"
IMAGE_RELATIVE_PATH = "chtc/time_dynamics_optuna/image.sif"
DEFAULT_SEGMENT_LENGTH = 0.5
DEFAULT_CAMPAIGN_FINAL_TIME = 4.0
DEFAULT_TIME_LABEL_SCALE = 1000.0
LANE_SOLVER_SETTING_PROFILE = "max_threads_8"
LANE_BUNDLE_SEED_POLICY = "monotone_hint"

_RUN_ID_RE = re.compile(
    r"^(?P<prefix>[A-Za-z0-9]+)"
    r"_s(?P<index>\d+)"
    r"_t(?P<start>\d+)_t(?P<end>\d+)"
    r"(?:_r(?P<resume>\d+))?$"
)

_SUBMIT_TEMPLATE = """\
# Paper V CWRMF bounded-depth event-triggered guard, balanced profile.
# {headline}
# Generated by {generator} on {generated_on} from
#   {source_relative}
# Source run id {source_run_id}, stop_reason {stop_reason}, last_time {last_time}.
# Argument contract: run_id final_time time_step event_gram_hard_floor \\
#   initial_state_file expected_initial_time.
universe = vanilla
executable = {lane}/run_cwrmf_event_guard_accel_apptainer.sh
arguments = {run_id} {final_time} {time_step} {hard_floor} {checkpoint} {expected_initial_time}
should_transfer_files = YES
when_to_transfer_output = ON_EXIT
transfer_executable = True
preserve_relative_paths = True
transfer_input_files = paper_5/src, {lane}, {image}, {checkpoint}
transfer_output_files = raw_outputs, logs, archives_by_receipt
{environment_line}stream_output = False
stream_error = False
log = logs/{campaign}.$(Cluster).$(Process).log
output = logs/{campaign}.{run_id}.$(Cluster).$(Process).out
error = logs/{campaign}.{run_id}.$(Cluster).$(Process).err
requirements = TARGET.HasSIF
request_cpus = 8
request_memory = 12GB
request_disk = 30GB
+MaxRuntime = 172800
+JobBatchName = "{campaign}-{run_id}"
queue 1
"""


class GeneratorError(RuntimeError):
    """Raised when the continuation cannot be written from what was given."""


def _read_json(path: Path) -> dict:
    try:
        with path.open(encoding="utf-8") as handle:
            return json.load(handle)
    except OSError as exc:  # pragma: no cover - surfaced verbatim
        raise GeneratorError(f"cannot read {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise GeneratorError(f"{path} is not valid JSON: {exc}") from exc


def load_returned_segment(path: Path) -> dict:
    """Read a receipt.json or a run's summary.json into one record.

    A receipt carries the run id and the campaign directly.  A summary does
    not, so they are read off its own path,
    ``raw_outputs/<campaign>/<run_id>/summary.json``, which is where the
    inner runner puts it.
    """

    document = _read_json(path)
    if "integration" in document and "numerical_settings" in document:
        integration = document["integration"]
        settings = document["numerical_settings"]
        if path.parent.parent.parent.name != "raw_outputs":
            raise GeneratorError(
                f"{path} is a summary.json but is not at "
                "raw_outputs/<campaign>/<run_id>/summary.json, so the run id "
                "and campaign cannot be read from its path; pass the "
                "receipt.json instead"
            )
        record = {
            "campaign": path.parent.parent.name,
            "run_id": path.parent.name,
            "final_time": float(integration["final_time_requested"]),
            "time_step": integration["time_step"],
            "event_gram_hard_floor": settings.get("event_gram_hard_floor"),
            "stop_reason": integration.get("stop_reason", "unrecorded"),
            "last_time": integration.get("last_time", "unrecorded"),
            "solver_setting_profile": settings.get(
                "solver_setting_profile", LANE_SOLVER_SETTING_PROFILE
            ),
            "bundle_seed_policy": settings.get(
                "bundle_seed_policy", LANE_BUNDLE_SEED_POLICY
            ),
            "bundle_seed_rank_margin": settings.get("bundle_seed_rank_margin"),
        }
    else:
        missing = [
            key
            for key in ("campaign", "run_id", "final_time", "time_step")
            if key not in document
        ]
        if missing:
            raise GeneratorError(
                f"{path} is neither a lane receipt.json nor a run "
                f"summary.json (missing {', '.join(missing)})"
            )
        record = {
            "campaign": document["campaign"],
            "run_id": document["run_id"],
            "final_time": float(document["final_time"]),
            "time_step": document["time_step"],
            "event_gram_hard_floor": document.get("event_gram_hard_floor"),
            "stop_reason": document.get("stop_reason", "unrecorded"),
            "last_time": document.get("last_time", "unrecorded"),
            "solver_setting_profile": document.get(
                "solver_setting_profile", LANE_SOLVER_SETTING_PROFILE
            ),
            "bundle_seed_policy": document.get(
                "bundle_seed_policy", LANE_BUNDLE_SEED_POLICY
            ),
            "bundle_seed_rank_margin": document.get("bundle_seed_rank_margin"),
        }
    if record["event_gram_hard_floor"] in (None, "", "none"):
        raise GeneratorError(
            f"{path} records no event_gram_hard_floor; the lane's guard "
            "configuration cannot be reproduced from it"
        )
    return record


def parse_run_id(run_id: str) -> dict:
    """Split a lane run id into prefix, segment index, time labels, resume."""

    match = _RUN_ID_RE.match(run_id)
    if match is None:
        raise GeneratorError(
            f"run id {run_id!r} is not of the lane's form "
            "<prefix>_s<NN>_t<start>_t<end>[_r<NN>]; a continuation cannot "
            "be named from it"
        )
    return {
        "prefix": match.group("prefix"),
        "index": int(match.group("index")),
        "start": match.group("start"),
        "end": match.group("end"),
        "resume": int(match.group("resume")) if match.group("resume") else 0,
    }


def _time_label(value: float, scale: float) -> str:
    return f"{round(value * scale):04d}"


def known_run_ids(submit_root: Path, campaign: str, lane_directory: Path) -> set[str]:
    """Every run id this submit root has already produced or already names.

    Two sources, because either one alone can miss a reuse: the run
    directories under ``raw_outputs/<campaign>/`` are what a stage-out would
    replace, and the ``arguments`` line of every submit file in the lane is
    what a submission would claim.
    """

    found: set[str] = set()
    campaign_directory = submit_root / "raw_outputs" / campaign
    if campaign_directory.is_dir():
        found.update(
            entry.name for entry in campaign_directory.iterdir() if entry.is_dir()
        )
    if lane_directory.is_dir():
        for submit_file in sorted(lane_directory.glob("*.sub")):
            for line in submit_file.read_text(encoding="utf-8").splitlines():
                stripped = line.strip()
                if stripped.lower().startswith("arguments"):
                    fields = stripped.split("=", 1)[1].split()
                    if fields:
                        found.add(fields[0])
    return found


def choose_run_id(record: dict, kind: str, taken: set[str], options) -> tuple[str, dict]:
    """Name the continuation's run id and say what interval it covers."""

    parts = parse_run_id(record["run_id"])
    if kind == "resume":
        attempt = max(parts["resume"], 0) + 1
        while attempt < 100:
            candidate = (
                f"{parts['prefix']}_s{parts['index']:02d}"
                f"_t{parts['start']}_t{parts['end']}_r{attempt:02d}"
            )
            if candidate not in taken:
                return candidate, {
                    "final_time": record["final_time"],
                    "expected_initial_time": record["last_time"],
                    "headline": (
                        f"Resume {attempt} of segment {parts['index']:02d}: "
                        f"continue to t = {record['final_time']:g} at "
                        f"h = {record['time_step']} from the checkpoint "
                        f"{record['run_id']} left at t = {record['last_time']}."
                    ),
                }
            attempt += 1
        raise GeneratorError(
            f"segment {parts['index']:02d} already has 99 resumes; stop and "
            "read why it is not advancing"
        )
    campaign_final_time = options.campaign_final_time
    final_time = min(record["final_time"] + options.segment_length, campaign_final_time)
    if record["final_time"] >= campaign_final_time - 1e-12:
        raise GeneratorError(
            f"{record['run_id']} reached the campaign's final time "
            f"{campaign_final_time:g}; there is no next segment"
        )
    candidate = (
        f"{parts['prefix']}_s{parts['index'] + 1:02d}"
        f"_t{parts['end']}_t{_time_label(final_time, options.time_label_scale)}"
    )
    if candidate in taken:
        raise GeneratorError(
            f"the next segment's run id {candidate} is already used in this "
            "submit root; that segment has already been generated or "
            "submitted, so nothing is written"
        )
    return candidate, {
        "final_time": final_time,
        "expected_initial_time": record["final_time"],
        "headline": (
            f"Segment {parts['index'] + 1:02d}: t = {record['final_time']:g} to "
            f"{final_time:g} at h = {record['time_step']}, event Gram hard "
            f"floor {record['event_gram_hard_floor']}, bounded step halving "
            "at depth 2."
        ),
    }


def environment_line(record: dict, maximum_wall_seconds: float | None) -> str:
    """Carry a non-default configuration into the continuation.

    Resuming under a different seed policy or solver setting set than the
    segment that wrote the checkpoint is a configuration change, not a
    continuation, so anything the returned segment resolved away from the
    lane default is restated here.
    """

    entries: list[str] = []
    if record["solver_setting_profile"] != LANE_SOLVER_SETTING_PROFILE:
        entries.append(
            f"CWRMF_SOLVER_SETTING_PROFILE={record['solver_setting_profile']}"
        )
    if record["bundle_seed_policy"] != LANE_BUNDLE_SEED_POLICY:
        entries.append(f"CWRMF_BUNDLE_SEED_POLICY={record['bundle_seed_policy']}")
        if record["bundle_seed_rank_margin"] not in (None, "", "none"):
            entries.append(
                "CWRMF_BUNDLE_SEED_RANK_MARGIN="
                f"{record['bundle_seed_rank_margin']}"
            )
    if maximum_wall_seconds is not None:
        entries.append(f"CWRMF_MAXIMUM_WALL_SECONDS={maximum_wall_seconds:g}")
    if not entries:
        return ""
    return 'environment = "' + " ".join(entries) + '"\n'


def _expected_initial_time_field(plan: dict) -> str:
    """The time the continuation's checkpoint must hold, or "none".

    A stopped segment's receipt records last_time as a full-precision float;
    a finished one's own final_time is the next segment's start.  Either is
    handed to the driver as --initial-time, which refuses a checkpoint that
    disagrees with it.
    """

    value = plan.get("expected_initial_time")
    if value in (None, "", "unrecorded", "none"):
        return "none"
    # repr is the shortest decimal that reads back as the same double, so the
    # submit file carries the checkpoint's own time and nothing longer.
    return repr(float(value))


def build_submit_text(record: dict, run_id: str, plan: dict, source: Path, options) -> str:
    checkpoint = (
        f"raw_outputs/{record['campaign']}/{record['run_id']}/checkpoint.npz"
    )
    try:
        source_relative = source.resolve().relative_to(options.submit_root.resolve())
    except ValueError:
        source_relative = source
    return _SUBMIT_TEMPLATE.format(
        headline=plan["headline"],
        generator=f"{LANE_RELATIVE_PATH}/make_resume_submit.py",
        generated_on=options.generated_on,
        source_relative=source_relative,
        source_run_id=record["run_id"],
        stop_reason=record["stop_reason"],
        last_time=record["last_time"],
        lane=options.lane_relative_path,
        image=options.image_relative_path,
        run_id=run_id,
        final_time=f"{plan['final_time']:g}",
        time_step=record["time_step"],
        hard_floor=record["event_gram_hard_floor"],
        checkpoint=checkpoint,
        expected_initial_time=_expected_initial_time_field(plan),
        environment_line=environment_line(record, options.maximum_wall_seconds),
        campaign=record["campaign"],
    )


def resolve_kind(record: dict, requested: str) -> str:
    if requested != "auto":
        return requested
    stop_reason = record["stop_reason"]
    if stop_reason == "wall_budget":
        return "resume"
    if stop_reason == "final_time":
        return "next"
    raise GeneratorError(
        f"{record['run_id']} returned stop_reason {stop_reason!r}; only "
        "wall_budget and final_time continue the campaign on their own.  "
        "step_failure needs the atom's message in summary.json read first, "
        "and unrecorded means the driver died before writing it.  Pass "
        "--kind resume or --kind next once the failure is understood."
    )


def parse_arguments(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Write this lane's continuation submit file from a returned "
            "segment's receipt.json or summary.json."
        )
    )
    parser.add_argument(
        "source", type=Path, help="receipt.json of a returned segment, or its summary.json"
    )
    parser.add_argument(
        "--kind",
        choices=("auto", "resume", "next"),
        default="auto",
        help=(
            "auto reads stop_reason: wall_budget gives a resume of the same "
            "segment, final_time gives the next segment"
        ),
    )
    parser.add_argument(
        "--submit-root",
        type=Path,
        default=None,
        help=(
            "the directory the job runs from; defaults to the receipt's own "
            "submit root (two levels above archives_by_receipt/<sha>/) or the "
            "current directory"
        ),
    )
    parser.add_argument(
        "--lane-directory",
        type=Path,
        default=None,
        help="where to write the submit file; defaults to the lane under the submit root",
    )
    parser.add_argument(
        "--lane-relative-path", default=LANE_RELATIVE_PATH,
        help="the lane path the submit file names for transfer",
    )
    parser.add_argument(
        "--image-relative-path", default=IMAGE_RELATIVE_PATH,
        help="the Apptainer image path the submit file names for transfer",
    )
    parser.add_argument("--segment-length", type=float, default=DEFAULT_SEGMENT_LENGTH)
    parser.add_argument(
        "--campaign-final-time", type=float, default=DEFAULT_CAMPAIGN_FINAL_TIME
    )
    parser.add_argument(
        "--time-label-scale",
        type=float,
        default=DEFAULT_TIME_LABEL_SCALE,
        help="run ids label a time t as round(t * scale) in four digits",
    )
    parser.add_argument(
        "--maximum-wall-seconds",
        type=float,
        default=None,
        help=(
            "shorten the continuation's wall budget; omitted, the inner "
            "runner's lane default of 138240 s applies"
        ),
    )
    parser.add_argument(
        "--date",
        dest="generated_on",
        default=None,
        help="the date the written file name carries; defaults to today",
    )
    parser.add_argument(
        "--allow-missing-checkpoint",
        action="store_true",
        help=(
            "write the file even when the checkpoint it resumes from is not "
            "in the submit root yet"
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print the submit file instead of writing it",
    )
    args = parser.parse_args(argv)
    if args.generated_on is None:
        args.generated_on = date.today().isoformat()
    return args


def main(argv: list[str] | None = None) -> int:
    options = parse_arguments(argv)
    try:
        source = options.source
        if not source.is_file():
            raise GeneratorError(f"{source} is not a file")
        record = load_returned_segment(source)
        if options.submit_root is None:
            parents = source.resolve().parents
            if len(parents) >= 3 and parents[1].name == "archives_by_receipt":
                options.submit_root = parents[2]
            elif len(parents) >= 3 and parents[2].name == "raw_outputs":
                options.submit_root = parents[3]
            else:
                options.submit_root = Path.cwd()
        if options.lane_directory is None:
            options.lane_directory = options.submit_root / options.lane_relative_path
        kind = resolve_kind(record, options.kind)
        checkpoint = (
            options.submit_root
            / "raw_outputs"
            / record["campaign"]
            / record["run_id"]
            / "checkpoint.npz"
        )
        if not checkpoint.is_file() and not options.allow_missing_checkpoint:
            raise GeneratorError(
                f"the checkpoint the continuation resumes from is not here: "
                f"{checkpoint}.  Collect the segment first, or pass "
                "--allow-missing-checkpoint to write the file anyway"
            )
        taken = known_run_ids(
            options.submit_root, record["campaign"], options.lane_directory
        )
        run_id, plan = choose_run_id(record, kind, taken, options)
        text = build_submit_text(record, run_id, plan, source, options)
        target = (
            options.lane_directory
            / f"submit_cwrmf_accel_{run_id}_{options.generated_on.replace('-', '')}.sub"
        )
        if options.dry_run:
            sys.stdout.write(text)
            print(f"would write {target}")
            return 0
        if target.exists():
            raise GeneratorError(
                f"{target} already exists; a generated submit file is never "
                "overwritten"
            )
        options.lane_directory.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        print(f"kind={kind} run_id={run_id} final_time={plan['final_time']:g}")
        print(target)
    except GeneratorError as exc:
        print(f"make_resume_submit: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
