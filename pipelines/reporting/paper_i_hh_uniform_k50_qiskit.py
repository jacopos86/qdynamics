#!/usr/bin/env python3
"""Uniform round-50 Qiskit compilation for Paper-I insertion overlays.

The historical overlay inputs were generated by more than one reporting
adapter.  Some adapters compiled Pauli labels in serialized/native order,
whereas the runtime parameterization and the current Paper-I compiler use
coefficient-bearing generators in deterministic runtime order.  This module
normalizes every RA endpoint through the current execution-aware compiler and
validates saved Append endpoints against the same compiler fingerprint.
"""

