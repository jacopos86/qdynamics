"""Exact linear reductions and conserved-system diagnostics of the archive field.

Works on the explicit polynomial form of ``closed_scalar_rhs``
(:class:`~paper5.stability.quantum_target_form.ClosedPolynomialForm`).  It
provides the two exact linear reductions of the 31 closed coordinates:

* the decoupled centre-mode coherent field ``B_+ = B_0 + B_1``, which obeys
  ``dB_+/dt = -i omega B_+ - 2 i g`` exactly;
* the one linear first integral ``ell``, which eliminates
  ``correlation_shared_trace_real``;

and the diagnostics the conserved-system Carleman theorems ask for:

* neutral-mode projections of the forcing and the quadratic term;
* order-two resonances with their quadratic coupling;
* the matrix Lie algebra generated by the linear part and the drive, with an
  isotropic element of its trace form, which excludes a common skew-adjoint
  metric;
* the signed-sector partition.

Exact references never enter.  Nothing here changes a default.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from scipy.linalg import expm, null_space

from .hubbard_dimer import FloatArray
from .matrix_reference import CLOSED_SCALAR_STATE_NAMES
from .quantum_target_form import ClosedPolynomialForm, extract_cubic_polynomial

N_CLOSED = len(CLOSED_SCALAR_STATE_NAMES)
_INDEX = {name: i for i, name in enumerate(CLOSED_SCALAR_STATE_NAMES)}
B0R, B0I = _INDEX["coherent_0_real"], _INDEX["coherent_0_imag"]
B1R, B1I = _INDEX["coherent_1_real"], _INDEX["coherent_1_imag"]
SHARED_TRACE_REAL = _INDEX["correlation_shared_trace_real"]


def centre_mode_basis() -> tuple[FloatArray, FloatArray]:
    """Return ``(S, S_inv)`` with ``x = S z``.

    In ``z`` the coherent slots hold ``Re B_+``, ``Im B_+`` (at the indices of
    ``coherent_0``) and ``Re B_-``, ``Im B_-`` (at those of ``coherent_1``),
    with ``B_+- = B_0 +- B_1``; every other coordinate is unchanged.
    """

    s = np.eye(N_CLOSED)
    for zero, one in ((B0R, B1R), (B0I, B1I)):
        s[zero, zero] = 0.5
        s[zero, one] = 0.5
        s[one, zero] = 0.5
        s[one, one] = -0.5
    return s, np.linalg.inv(s)


def linear_first_integral(form: ClosedPolynomialForm) -> tuple[FloatArray, FloatArray]:
    """Left null vector of ``[F_0 | A_1 | A_2 | D]``, scaled to 1 on the real
    shared trace of ``C``; also returns the singular values of that matrix."""

    stacked = np.hstack(
        [form.constant[:, None], form.linear_free, form.quadratic_matrix(), form.linear_drive]
    )
    u, singular, _ = np.linalg.svd(stacked)
    ell = u[:, -1] / u[SHARED_TRACE_REAL, -1]
    return ell, singular


@dataclass(frozen=True)
class ReducedForm:
    """The field on the 28 coordinates left by both exact linear reductions.

    ``keep`` indexes ``z``; ``b_plus`` is the fixed value of ``(Re B_+, Im B_+)``
    and ``ell_value`` the fixed value of ``ell . x``.  The reduced field is
    ``constant + linear y + quadratic(y, y) + f(t) (drive y + drive_offset)``.
    """

    keep: tuple[int, ...]
    ell: FloatArray
    ell_value: float
    b_plus: FloatArray
    constant: FloatArray
    linear: FloatArray
    quadratic: FloatArray
    drive: FloatArray
    drive_offset: FloatArray
    s: FloatArray
    s_inv: FloatArray

    @property
    def dimension(self) -> int:
        return len(self.keep)

    def embed(self, y: FloatArray) -> FloatArray:
        z = np.zeros(N_CLOSED)
        z[list(self.keep)] = y
        z[B0R], z[B0I] = self.b_plus
        x = self.s @ z
        x[SHARED_TRACE_REAL] = 0.0
        x[SHARED_TRACE_REAL] = (self.ell_value - self.ell @ x) / self.ell[SHARED_TRACE_REAL]
        return x

    def restrict(self, x: FloatArray) -> FloatArray:
        return (self.s_inv @ np.asarray(x, dtype=float))[list(self.keep)]

    def evaluate(self, time: float, y: FloatArray, drive_value: float) -> FloatArray:
        y = np.asarray(y, dtype=float)
        return (
            self.constant
            + self.linear @ y
            + np.einsum("mij,i,j->m", self.quadratic, y, y)
            + drive_value * (self.drive @ y + self.drive_offset)
        )


def reduce_at_centre_mode_fixed_point(
    form: ClosedPolynomialForm,
    reference_state: FloatArray,
) -> ReducedForm:
    """Fix ``B_+`` at ``-2 g / omega`` and ``ell`` at its value on the reference.

    ``B_+`` is exactly decoupled; it is fixed at its stationary value, so a
    trajectory whose ``B_+`` oscillates about that value is reproduced only up
    to that oscillation's amplitude.
    """

    parameters = form.parameters
    s, s_inv = centre_mode_basis()
    ell, _ = linear_first_integral(form)
    ell_value = float(ell @ np.asarray(reference_state, dtype=float))
    keep = tuple(i for i in range(N_CLOSED) if i not in (B0R, B0I, SHARED_TRACE_REAL))
    b_plus = np.array([-2.0 * parameters.coupling / parameters.omega_ph, 0.0])
    provisional = ReducedForm(
        keep=keep, ell=ell, ell_value=ell_value, b_plus=b_plus,
        constant=np.zeros(len(keep)), linear=np.zeros((len(keep), len(keep))),
        quadratic=np.zeros((len(keep),) * 3), drive=np.zeros((len(keep), len(keep))),
        drive_offset=np.zeros(len(keep)), s=s, s_inv=s_inv,
    )
    free = extract_cubic_polynomial(
        lambda y: provisional.restrict(_drive_free(form, provisional.embed(y))), len(keep)
    )
    drive = extract_cubic_polynomial(
        lambda y: provisional.restrict(form.linear_drive @ provisional.embed(y)), len(keep)
    )
    return ReducedForm(
        keep=keep, ell=ell, ell_value=ell_value, b_plus=b_plus,
        constant=free.constant, linear=free.linear, quadratic=free.quadratic,
        drive=drive.linear, drive_offset=drive.constant, s=s, s_inv=s_inv,
    )


def _drive_free(form: ClosedPolynomialForm, x: FloatArray) -> FloatArray:
    return (
        form.constant
        + form.linear_free @ x
        + form.quadratic_matrix() @ np.outer(x, x).reshape(-1)
    )


def _rank(matrix: FloatArray, relative: float = 1e-10) -> int:
    singular = np.linalg.svd(matrix, compute_uv=False)
    return int(np.sum(singular > relative * singular[0]))


def neutral_mode_report(constant: FloatArray, linear: FloatArray, quadratic: FloatArray) -> dict:
    """Ranks and the projections of forcing and quadratic term on the left
    null space of the linear part (the neutral zero modes)."""

    n = linear.shape[0]
    q = quadratic.reshape(n, -1)
    u, singular, _ = np.linalg.svd(linear)
    rank = int(np.sum(singular > 1e-10 * singular[0]))
    left_null = u[:, rank:]
    projection = left_null.T @ q
    projection_singular = np.linalg.svd(projection, compute_uv=False) if left_null.shape[1] else np.zeros(0)
    eigenvalues = np.linalg.eigvals(linear)
    return {
        "rank_linear": rank,
        "rank_forcing_linear": _rank(np.hstack([constant[:, None], linear])),
        "rank_forcing_linear_quadratic": _rank(np.hstack([constant[:, None], linear, q])),
        "left_null_dimension": int(left_null.shape[1]),
        "forcing_projection_norm": float(np.linalg.norm(left_null.T @ constant)),
        "quadratic_projection_singular_values": [float(v) for v in projection_singular],
        "trace_linear": float(np.trace(linear)),
        "max_abs_diagonal_linear": float(np.max(np.abs(np.diag(linear)))),
        "max_abs_real_eigenvalue": float(np.max(np.abs(eigenvalues.real))),
        "zero_eigenvalues": int(np.sum(np.abs(eigenvalues) < 1e-9)),
    }


def order_two_resonances(linear: FloatArray, quadratic: FloatArray, tolerance: float = 1e-10) -> dict:
    """Ordered eigenvalue pairs with ``lambda_c = lambda_a + lambda_b`` and the
    norm of the quadratic coupling projected on them (orthonormal eigenspace
    bases from null spaces, so degenerate clusters are handled)."""

    k = linear.shape[0]
    eigenvalues = np.linalg.eigvals(linear)
    clusters: list[complex] = []
    for value in eigenvalues:
        if not any(abs(value - c) < 1e-6 for c in clusters):
            clusters.append(complex(value))
    right = {c: null_space(linear - c * np.eye(k), rcond=1e-9) for c in clusters}
    left = {c: null_space((linear - c * np.eye(k)).conj().T, rcond=1e-9) for c in clusters}
    hits = []
    for a in clusters:
        for b in clusters:
            for c in clusters:
                if abs(c - a - b) < 1e-8:
                    block = np.einsum("mk,mij,ia,jb->kab", left[c].conj(), quadratic, right[a], right[b])
                    block = block + np.einsum("mk,mji,ia,jb->kab", left[c].conj(), quadratic, right[a], right[b])
                    hits.append((a, b, c, float(np.linalg.norm(block))))
    nonzero = [h for h in hits if h[3] > tolerance]
    return {
        "resonant_ordered_pairs": len(hits),
        "with_nonzero_quadratic_coupling": len(nonzero),
        "nonzero_with_a_zero_input": sum(1 for h in nonzero if abs(h[0]) < 1e-9 or abs(h[1]) < 1e-9),
        "smallest_nonzero_coupling": min((h[3] for h in nonzero), default=None),
        "largest_vanishing_coupling": max((h[3] for h in hits if h[3] <= tolerance), default=None),
    }


def generated_lie_algebra(matrices: list[FloatArray], tolerance: float = 1e-9, limit: int = 600) -> list[FloatArray]:
    """Frobenius-orthonormal basis of the matrix Lie algebra the inputs generate."""

    basis: list[FloatArray] = []

    def add(x: FloatArray) -> bool:
        v = x.reshape(-1).copy()
        for _ in range(2):
            for b in basis:
                v -= (b.reshape(-1) @ v) * b.reshape(-1)
        norm = np.linalg.norm(v)
        if norm > tolerance * max(1.0, np.linalg.norm(x)):
            basis.append((v / norm).reshape(x.shape))
            return True
        return False

    for m in matrices:
        add(np.asarray(m, dtype=float))
    frontier = list(range(len(basis)))
    while frontier and len(basis) < limit:
        new = []
        count = len(basis)
        for i in range(count):
            for j in frontier:
                if j <= i and i in frontier:
                    continue
                if add(basis[i] @ basis[j] - basis[j] @ basis[i]):
                    new.append(len(basis) - 1)
        frontier = new
    return basis


def common_metric_obstruction(matrices: list[FloatArray]) -> dict:
    """A positive ``G`` making every input skew-adjoint makes the whole
    generated algebra skew-adjoint, so its trace form ``tr(X Y)`` is negative
    definite.  Returns the algebra dimension, the largest trace-form eigenvalue,
    and the top eigen-element ``X`` with ``||X^2||`` and ``||exp(t X)||``: an
    ``X`` with ``X^2 = 0`` and ``exp(t X)`` unbounded excludes every such ``G``."""

    basis = generated_lie_algebra(matrices)
    form = np.array([[np.trace(x @ y) for y in basis] for x in basis])
    values, vectors = np.linalg.eigh(0.5 * (form + form.T))
    top = sum(c * b for c, b in zip(vectors[:, -1], basis))
    top = top / np.linalg.norm(top)
    return {
        "algebra_dimension": len(basis),
        "trace_form_largest_eigenvalue": float(values[-1]),
        "trace_form_nonnegative_count": int(np.sum(values >= -1e-10)),
        "top_element_square_frobenius": float(np.linalg.norm(top @ top)),
        "top_element_exp_norms": {str(t): float(np.linalg.norm(expm(t * top), 2)) for t in (1, 10, 100, 1000)},
    }


def skew_adjoint_metric_dimension(matrices: list[FloatArray]) -> int:
    """Dimension of the symmetric ``G`` with ``X^T G + G X = 0`` for every input."""

    k = matrices[0].shape[0]
    basis = []
    for i in range(k):
        for j in range(i, k):
            e = np.zeros((k, k))
            e[i, j] = e[j, i] = 1.0
            basis.append(e)
    rows = np.vstack([np.array([(x.T @ e + e @ x).reshape(-1) for e in basis]).T for x in matrices])
    return int(null_space(rows, rcond=1e-10).shape[1])


def signed_sector_report(linear: FloatArray, quadratic: FloatArray) -> dict:
    """The signed-sector partition of the conserved-system Carleman theorem.

    A mode can join ``S+`` only if ``Re < 0`` or ``Im > 0``, and ``S-`` only if
    ``Re < 0`` or ``Im < 0``; a mode with ``Re >= 0`` and ``Im = 0`` fits
    neither.  For the partition by the sign of ``Im`` (zero modes left out),
    returns the share of the eigenbasis-transformed quadratic tensor outside the
    allowed blocks ``P+ F2 (P+ (x) P+)`` and ``P- F2 (P- (x) P-)``.
    """

    eigenvalues, vectors = np.linalg.eig(linear)
    inverse = np.linalg.inv(vectors)
    fits_neither = (eigenvalues.real >= -1e-9) & (np.abs(eigenvalues.imag) < 1e-9)
    plus = (eigenvalues.imag > 1e-9) | (eigenvalues.real < -1e-9)
    minus = (eigenvalues.imag < -1e-9)
    transformed = np.einsum("km,mij,ia,jb->kab", inverse, quadratic, vectors, vectors)
    allowed = np.zeros_like(transformed, dtype=bool)
    allowed[np.ix_(plus, plus, plus)] = True
    allowed[np.ix_(minus, minus, minus)] = True
    total = float(np.linalg.norm(transformed))
    outside = float(np.linalg.norm(transformed[~allowed]))
    return {
        "modes": int(eigenvalues.size),
        "modes_fitting_neither_sector": int(np.sum(fits_neither)),
        "positive_imaginary_modes": int(np.sum(plus)),
        "negative_imaginary_modes": int(np.sum(minus)),
        "quadratic_share_outside_allowed_blocks": outside / total if total else 0.0,
    }
